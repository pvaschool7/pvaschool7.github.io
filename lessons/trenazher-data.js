function checkNum(input,answer){
 var s=String(input==null?"":input).trim();
 if(!s)return false;
 s=s.replace(/,/g,".").replace(/\u2212/g,"-").replace(/\s+/g,"");
 if(!/^-?\d+(\.\d+)?$/.test(s))return false;
 return Math.abs(parseFloat(s)-answer)<1e-9;
}

